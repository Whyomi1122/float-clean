/**
 * 群像文风（内置常驻）
 * ────────────────────────────────────────────────────────────
 * 来源：外部资料《现代群像文风 · 众生相 by 花辞树》（作者许可二改自用），
 * 2026-11-24 由主窗口裁剪成 float 可用的两档，**自动挂载、不给用户开关**：
 *
 *   A  + B1  →  所有剧本（含单人剧本；单人也会有 NPC 出场）
 *   A  + B1 + B2  →  参演阵容 ≥ 2 人（真正的群像场面）
 *
 * 设计约束（别破坏）：
 *  - 只讲「怎么写」，不碰画风、不碰格式暗号（那些在 systemPrompt 里有专门铁律）；
 *  - 用户自己的世界书 / 预设永远在后面、优先级更高，这里只当默认底色；
 *  - 文案要短：整块 ≤ 1500 字，长了会挤占上下文。
 */

/** A · 通用写法：任何剧本都适用 */
const STYLE_BASE = `【一 · 先有空间，再有人】每场戏开头用一句话把场地立住：谁在门口、谁靠着柜台、谁坐在沙发哪一端。人物不许悬空对话，读者要能画出这张图。场地没变就不要反复描写。

【二 · 台词藏三分】角色说出口的话，通常不等于心里那句话。想留住一个人，嘴上说的是"随便你"；担心对方淋雨，嘴上说的是"伞拿着"。日常寒暄可以有，但别让寒暄占满整段对话——台词要往关系上使劲。

【三 · 情绪用动作写】不写"他很生气""她很委屈""气氛很尴尬"这类判断，写他把杯子顿在桌上、她笑了一下却没抬眼、两个人之间那半米谁都没动。叙述和动作块里**不要下情绪结论**（心理块里让角色自己想，是允许的）。

【四 · 禁止说书腔】不写"仿佛""似乎""不禁""像是在诉说什么"这种替角色解释的句子；不总结这一场意味着什么；不复述刚发生过的对话。一个动作写完就停，不要补一句"这让她意识到……"。

【五 · 人物要有自己的小动作】给每个角色一个反复出现的小习惯（转笔、捋袖口、开口前清一下嗓子）。不要所有人都一样地"看着她""轻声说"。

【六 · 收尾不要升华】一幕在动作或一句台词上结束就好，不写"夜还很长""这一夜注定无眠"这类总结句。`;

/** B1 · 距离感：所有剧本都挂（单人剧本靠这段把 NPC 写出戏） */
const STYLE_DISTANCE = `【七 · 谁知道什么】信息要分层：有人当面说的、有人压低声音说的、有人从别人嘴里听来的、有人说错了的。角色只按自己**该知道的**说话和反应，不许凭空知道别人的私事。

【八 · 谁在看谁】写清目光走向：谁在躲谁的眼睛、谁一直盯着门口、谁看不见背后的表情。距离感就是靠这个出来的。

【九 · 配角要有来意】出现的每个人（店员、同事、邻居、路人）都要有目的：报信、阻拦、添乱、看热闹。不许当背景板晃过去，也不许凭空变成关键人物。`;

/** B2 · 多人戏：仅参演阵容 ≥ 2 人时追加 */
const STYLE_ENSEMBLE = `【十 · 视角跟着动作走】谁在动，就多给他两句；其他人只给动作和反应，不要平均分配笔墨。

【十一 · 不许排队发言】多人场面必须交错：抢话、打断、把话岔开、两个人几乎同时开口、有人说了一半又咽回去。禁止"甲说完乙说、乙说完丙说"的轮流点名。

【十二 · 各有各的目的】同一场里，每个人想要的东西不一样，说出来的话也不要全都围着主角转。`;

/**
 * 生成要拼进群像 systemPrompt 的文风块。
 * @param castCount 参演阵容人数（`script.cast.length`）
 */
export function buildEnsembleStyleBlock(castCount: number): string {
    const multi = Number.isFinite(castCount) && castCount >= 2;
    return [
        "═══════════ 文风 · 写法规范（默认底色） ═══════════",
        "下面的规矩管的是**怎么写**，不改变上面的格式契约（归属行 + 五种暗号块）与任何既定事实。",
        "用户自己的文风要求、世界书里的写法规定，与这里冲突时以用户为准。",
        "",
        STYLE_BASE,
        "",
        STYLE_DISTANCE,
        ...(multi ? ["", STYLE_ENSEMBLE] : []),
    ].join("\n");
}
